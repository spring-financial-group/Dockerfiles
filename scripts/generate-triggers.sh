#!/usr/bin/env bash
# Regenerates .lighthouse/jenkins-x/triggers.yaml with a PR and release job for every dockerfiles/<category>/<image>/Dockerfile.
# The image name is the dir basename, so it must be unique across categories.
# Release jobs share the PR jobs' run_if_changed so an image is only published when its PR job vetted it.
# The plain `release` job (tag + changelog) stays unconditional.
# Also regenerates .lighthouse/jenkins-x/update-baselines.yaml, with one scan task per image, and its manual
# `/test update-baselines` trigger.
set -euo pipefail

cd "$(dirname "$0")/.."
out=.lighthouse/jenkins-x/triggers.yaml
baselines_out=.lighthouse/jenkins-x/update-baselines.yaml

dirs=$(find dockerfiles -name Dockerfile -exec dirname {} \; | LC_ALL=C sort)

dups=$(printf '%s\n' "$dirs" | xargs -n1 basename | LC_ALL=C sort | uniq -d)
if [ -n "$dups" ]; then
  echo "Duplicate image names found (image name is the dir basename):" >&2
  echo "$dups" >&2
  exit 1
fi

{
  cat <<'EOF'
# Generated by scripts/generate-triggers.sh - do not edit by hand
apiVersion: config.lighthouse.jenkins-x.io/v1alpha1
kind: TriggerConfig
spec:
  presubmits:
EOF
  for dir in $dirs; do
    cat <<EOF
  - name: ${dir##*/}-pr
    optional: false
    run_if_changed: (LastAutoCommit|^${dir//\//\\/}\/.*$)
    source: "dockerfile-pr.yaml"
    pipeline_run_params:
    - name: IMAGE_DIR
      value_template: ${dir}
EOF
  done
  cat <<'EOF'
  - name: lint-pipelines
    context: "lint-pipelines"
    run_if_changed: '(\.lighthouse\/jenkins-x\/.*|^scripts\/generate-triggers\.sh$|^dockerfiles\/.*\/Dockerfile$)'
    optional: false
    trigger: (?m)^/test( all| lint-pipelines.*),?(s+|$)
    rerun_command: /test lint-pipelines
    source: "lint-pipelines.yaml"
  - name: update-baselines
    context: "update-baselines"
    always_run: false
    optional: true
    trigger: (?m)^/test( update-baselines.*),?(s+|$)
    rerun_command: /test update-baselines
    source: "update-baselines.yaml"
  postsubmits:
  - name: release
    source: "release.yaml"
    branches:
    - ^main$
    - ^master$
EOF
  for dir in $dirs; do
    cat <<EOF
  - name: ${dir##*/}-release
    run_if_changed: (LastAutoCommit|^${dir//\//\\/}\/.*$)
    source: "dockerfile-release.yaml"
    branches:
    - ^main$
    - ^master$
    pipeline_run_params:
    - name: IMAGE_DIR
      value_template: ${dir}
EOF
  done
} > "$out"

echo "Wrote $out"

# update-baselines.yaml: one clone task -> one scan task per image (in parallel, on a shared workspace) -> one commit
# task. Deliberately plain Tekton: every task is spelled out, no matrix or finally.
{
  cat <<'EOF'
# Generated by scripts/generate-triggers.sh - do not edit by hand
# Rescans every published :latest image against one trivydb snapshot and opens/updates a PR with the changed
# .docksec-baseline.json files. Always runs against main. Trigger with `/test update-baselines` on any PR.
apiVersion: tekton.dev/v1beta1
kind: PipelineRun
metadata:
  name: update-baselines
spec:
  pipelineSpec:
    tasks:
    # Clone main once, and extract one trivydb snapshot, into the shared workspace.
    - name: git-clone
      workspaces:
      - name: source
        workspace: source
      taskSpec:
        stepTemplate:
          name: ""
          resources: {}
          workingDir: /workspace/source
          env:
          - name: HOME
            value: /tekton/home
        steps:
        - image: jx3mqubebuild.azurecr.io/spring-financial-group/container-tools:latest
          name: clone-main
          env:
          - name: GIT_TOKEN
            valueFrom:
              secretKeyRef:
                name: tekton-git
                key: password
          script: |
            #!/bin/bash
            set -euo pipefail
            git config --global --add safe.directory "$PWD"
            git init -q .
            git remote add origin https://github.com/spring-financial-group/Dockerfiles.git
            # Token read from the environment at call time, so it never lands in the remote URL, git config or logs.
            git -c credential.helper='!f() { echo username=x-access-token; echo "password=${GIT_TOKEN}"; }; f' \
              fetch --depth 50 origin main
            git checkout -q -B main FETCH_HEAD
            echo ".baseline-run/" >> .git/info/exclude
            mkdir -p .baseline-run/failed .baseline-run/trivydb
            git log -1 --oneline
        - image: jx3mqubebuild.azurecr.io/ghcr-io/jenkins-x/trivydb:latest
          name: copy-vulns-db
          script: |
            #!/bin/sh
            set -e
            cp -R /trivydb/. .baseline-run/trivydb/
EOF
  for dir in $dirs; do
    name=${dir##*/}
    cat <<EOF
    - name: scan-${name}
      runAfter:
      - git-clone
      workspaces:
      - name: source
        workspace: source
      taskSpec:
        steps:
        - image: jx3mqubebuild.azurecr.io/spring-financial-group/baseline-updater:latest
          name: scan
          resources: {}
          workingDir: /workspace/source
          securityContext:
            runAsUser: 0
          env:
          - name: HOME
            value: /tekton/home
          - name: DOCKER_HOST
            value: tcp://localhost:2375
          - name: DOCKER_CONFIG
            value: /docker-config
          volumeMounts:
          - mountPath: /docker-config
            name: docker-config
          script: |
            #!/bin/bash
            # A failed scan keeps the old baseline and is recorded for the commit task, but doesn't fail this task.
            for _ in \$(seq 1 90); do docker info >/dev/null 2>&1 && break; sleep 2; done
            TRIVYDB_DIR=.baseline-run/trivydb scripts/create-baselines.sh --trivydb ${dir} \\
              || echo ${dir} > .baseline-run/failed/${name}
            exit 0
        sidecars:
        - name: docker-daemon
          image: docker:27-dind
          securityContext:
            privileged: true
          env:
          - name: DOCKER_TLS_CERTDIR
            value: ""
          volumeMounts:
          - mountPath: /var/lib/docker
            name: docker-lib
        volumes:
        - name: docker-config
          secret:
            secretName: tekton-container-registry-auth
            items:
            - key: .dockerconfigjson
              path: config.json
        - name: docker-lib
          emptyDir: {}
EOF
  done
  cat <<'EOF'
    # One commit with every changed baseline, pushed to the rolling PR branch.
    - name: commit-baselines
      runAfter:
EOF
  for dir in $dirs; do
    echo "      - scan-${dir##*/}"
  done
  cat <<'EOF'
      workspaces:
      - name: source
        workspace: source
      taskSpec:
        steps:
        - image: jx3mqubebuild.azurecr.io/spring-financial-group/container-tools:latest
          name: commit-and-pr
          resources: {}
          workingDir: /workspace/source
          env:
          - name: HOME
            value: /tekton/home
          - name: GIT_TOKEN
            valueFrom:
              secretKeyRef:
                name: tekton-git
                key: password
          script: |
            #!/bin/bash
            set -euo pipefail
            git config --global --add safe.directory "$PWD"
            cat .baseline-run/failed/* > /tmp/failed-images 2>/dev/null || true
            FAILED_FILE=/tmp/failed-images scripts/update-baselines-pr.sh
  workspaces:
  - name: source
    volumeClaimTemplate:
      spec:
        storageClassName: azurefile-csi-premium
        accessModes:
        - ReadWriteMany
        resources:
          requests:
            storage: 5Gi
  podTemplate: {}
  serviceAccountName: tekton-bot
  timeout: 3h0m0s
status: {}
EOF
} > "$baselines_out"

echo "Wrote $baselines_out"
